/**
 * BLiNX 2: Masters of Time & Space - Recompiled Game Entry Point
 *
 * This is the executable that hosts the recompiled game code, on Windows x64
 * and macOS arm64. Both hosts run the same boot sequence:
 *
 * 1. Install the crash handler (VEH on Windows, SIGBUS/SIGSEGV elsewhere)
 * 2. Load the original XBE file from disk
 * 3. Initialize the Xbox memory layout (map data sections to original VAs)
 * 4. Start the emulated APU (only with RECOMP_AC97_READY, on hosts that can
 *    service its MMIO faults: x86-64 Windows/Proton, POSIX arm64)
 * 5. Initialize the Xbox kernel replacement layer
 * 6. Set up game file paths for I/O redirection
 * 7. Initialize the kernel bridge (thunk table in Xbox memory)
 * 8. Initialize the stack pointer
 * 9. Call the game's original entry point (recompiled)
 *
 * Platform-specific code is confined to the host_* functions below; the boot
 * sequence itself is host_main() and is shared.
 *
 * The game-specific constants are BLINX2_ENTRY_POINT, BLINX2_XBE_PATH and
 * BLINX2_GAME_DIR below; report_fault() prints the crash diagnosis.
 *
 * XBE details (from the toolkit's xbe_parser):
 *   Title:       BLiNX 2: Masters Of Time & Space
 *   Title ID:    0x4D530065
 *   Base addr:   0x00010000
 *   Entry point: 0x0029A1DA
 *   Code size:   ~2875 KB (.text)
 *   Sections:    73 (most are embedded model/motion data: MDL*, MOT*, M##)
 *   Kernel imports: 121
 */

