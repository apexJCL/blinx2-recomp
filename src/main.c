/* Console entry point: every non-Windows host, and console builds on Windows
 * (for debugging -- lets you see printf output).
 *
 * POSIX: the process main thread belongs to the window. AppKit only runs its
 * event loop there, so xbox_HostWindowMain (toolkit fb_present_sdl.c) opens
 * an SDL window here and runs host_main -- the whole boot and the guest --
 * on a "guest-main" pthread. The crash handler's alternate stack and the
 * watchdog are set up inside host_main, so they follow the guest onto that
 * thread. RECOMP_HEADLESS=1 keeps the guest on this thread, as before. */

int main(int argc, char **argv)
{
    (void)argc;
    (void)argv;
    /* The initial thread, named first: the toolkit leaves its OS name alone
     * (renaming it breaks pgrep/ps). host_main then logs guest-main, on this
     * thread when headless or on Windows, on its own pthread when windowed. */
    recomp_env_init();   /* the environment, read once, before any thread */
    xbox_log_thread_role("process-main", 0);
    xbox_HostWindowSetTitle("BLiNX 2 (recomp)");
#if defined(_WIN32)
    return host_main();
#else
#if defined(__APPLE__) && defined(__aarch64__)
    /* RECOMP_THREAD_DUMP waits for SIGUSR1 on a thread of its own and blocks
     * it on the thread that installs it (now the guest's). Block it here as
     * well, before any thread exists, or it lands on the window thread and
     * the default action kills the process. Only where that dumper exists
     * (host_install_thread_dump): elsewhere a blocked SIGUSR1 would pend
     * forever instead of acting. */
    if (recomp_env(RENV_THREAD_DUMP)) {
        sigset_t set;
        sigemptyset(&set);
        sigaddset(&set, SIGUSR1);
        pthread_sigmask(SIG_BLOCK, &set, NULL);
    }
#endif
    return xbox_HostWindowMain(host_main);
#endif
}
