/* A required startup step failed: say which, and what to do, on stderr on
 * every host -- and in a dialog on Windows, where a GUI-subsystem launch may
 * have no console to read. */
static void host_report_fatal(const char *step, const char *detail)
{
    fprintf(stderr, "[FATAL] %s: %s\n", step, detail);
    fflush(stderr);
#if defined(_WIN32)
    MessageBoxA(NULL, detail, "Recomp", MB_ICONERROR);
#endif
}

/* ── Boot sequence (shared) ────────────────────────────────── */

static int host_main(void)
{
    void *xbe_data = NULL;
    size_t xbe_size = 0;

    /* RECOMP_STDIO_LOG=<path>: send stdout and stderr to a file (truncated).
     * Proton drops a game's stdio whatever its subsystem, so this is the only
     * way to see the boot log and crash reports there. Before anything prints. */
    int stdio_log_err = -1;   /* Windows only: did stderr reopen? */
    {
        const char *stdio_log = recomp_env(RENV_STDIO_LOG);
        if (stdio_log && *stdio_log) {
#if defined(_WIN32)
            /* A GUI-subsystem exe starts with no stderr descriptor
             * (_fileno(stderr) == -2), so there is nothing to _dup2 onto.
             * Reopen both streams instead, in append mode so that their
             * writes interleave rather than overwrite each other. */
            FILE *trunc = fopen(stdio_log, "w");
            if (trunc) fclose(trunc);
            if (freopen(stdio_log, "a", stdout))
                stdio_log_err = freopen(stdio_log, "a", stderr) != NULL;
#else
            if (freopen(stdio_log, "w", stdout))
                dup2(fileno(stdout), fileno(stderr));
#endif
        }
    }

    /* Unbuffered output for immediate visibility during debugging */
    setvbuf(stdout, NULL, _IONBF, 0);
    setvbuf(stderr, NULL, _IONBF, 0);
    if (stdio_log_err >= 0)
        printf("[BOOT] RECOMP_STDIO_LOG: stderr %s\n",
               stdio_log_err ? "redirected" : "NOT redirected");
    /* Deprecated names and bad keys found when the environment was read:
     * held until now, so they land in the log rather than a closed stderr. */
    recomp_env_flush_notes();

    printf("=== BLiNX 2 - Static Recompilation ===\n");
    printf("Loading XBE...\n");
    xbox_log_thread_role("guest-main", 0);

    /* Step 1: Crash diagnostics, before anything can fault */
    host_install_crash_handler();
    host_install_thread_dump();

    /* Step 2: Load XBE */
    if (!load_xbe(BLINX2_XBE_PATH, &xbe_data, &xbe_size)) {
        host_report_fatal("load XBE",
            "cannot read " BLINX2_XBE_PATH " (relative to the current "
            "directory). Run from the project root, with the game files in "
            BLINX2_GAME_DIR "/.");
        return 1;
    }
    printf("XBE loaded: %zu bytes\n", xbe_size);

    /* RECOMP_AC97_READY (default on) needs MMIO trapping: recomp_env turns
     * it off on hosts that cannot service it, saying so if it was asked for,
     * because MemoryLayoutInit would otherwise mark the APU page PROT_NONE
     * with nothing to answer the faults. */

    /* Step 3: Initialize Xbox memory layout */
    printf("Initializing Xbox memory layout...\n");
    /* Deliberate deviation from retail (64 MB): devkit RAM. All 73 XBE
     * sections are loaded at boot, including the 49 that are not preload and
     * that XeLoadSection pages in and out on hardware -- that paging is not
     * modeled -- so at 64 MB the heap is ~14 MB and the game fills it during
     * its first archive loads. See openspec change xdk-library-hle. At 128 MB
     * the RAM mirrors must stop short of the contig window at 0x80000000; on
     * Windows that is the toolkit's reservation path (proton/win-layout). */
    xbox_SetTotalRam(XBOX_DEVKIT_RAM);
    if (!xbox_MemoryLayoutInit(xbe_data, xbe_size)) {
        host_report_fatal("map Xbox memory layout",
            "failed to initialize the Xbox memory layout. The required "
            "virtual address range may be unavailable.");
        free(xbe_data);
        return 1;
    }

    g_xbox_mem_offset = xbox_GetMemoryOffset();
    printf("Xbox memory mapped. Offset: 0x%llX\n", (unsigned long long)g_xbox_mem_offset);
    host_install_mem_dump();

    /* D3D's GPU completion fence. The device pointer is at 0x2F1FB8. The
     * device holds the last fence it submitted at +0x2C and, at +0x30, a
     * pointer to the word the GPU writes as it completes work (contiguous
     * memory, 0x80000000 in practice). The fence wait in sub_002E8110
     * spins until that word catches up.
     *
     * With RECOMP_PB_EXEC the toolkit's pushbuffer executor writes that word
     * itself when it reaches NV097_BACK_END_WRITE_SEMAPHORE_RELEASE (D3D
     * points the semaphore at offset 0 of the contiguous window, i.e. at
     * 0x80000000), and this mirror steps aside after the first release.
     * It stays registered as the fallback: with the executor off nothing
     * consumes the pushbuffer, so mirroring submitted -> completed, as the
     * toolkit does for Wreckless, is the only way the wait can end. Without
     * either, the main thread hangs there after the archive load (the word
     * stays 0xDEADBEEF). See openspec change present-frames. */
    xbox_Nv2aMirrorFence(0x2F1FB8, 0x2C, 0x30);

    /* The vblank interrupt, which the toolkit only raises on request. The
     * main loop (sub_0005F960 at 0x00060475) waits for the frame counter at
     * 0xAE7388 to move. Only the callback the title registers through
     * D3DDevice_SetVerticalBlankCallback (sub_000604A0) moves it, and D3D's
     * vblank DPC calls that callback. Without the interrupt the loop spins
     * forever. An explicit RECOMP_VBLANK in the environment still wins. */
    if (!recomp_env(RENV_VBLANK))
        recomp_env_set(RENV_VBLANK, "1");

#if HOST_CAN_SERVICE_MMIO
    /* Step 4: Bring up the emulated APU.
     *
     * Gated on the same variable that unmaps its registers, because the two
     * halves are useless apart: a trap with no model declines every access,
     * and a model nothing traps into never sees a register. The APU walks
     * Xbox physical RAM to find voice buffers, so it gets the guest RAM
     * base. */
    if (recomp_env(RENV_AC97_READY)) {
        g_apu_state = mcpx_apu_init_standalone((uint8_t *)xbox_GetMemoryBase());
        fprintf(stderr, "[BOOT] emulated APU %s\n",
                g_apu_state ? "up" : "FAILED to initialise");
        /* Its interrupt (audio task 4.7) and the contiguous window are the
         * toolkit's: the APU frame thread delivers vector 5 itself. */
        /* Diagnostic: the cost of one trapped APU access (audio spike 1.4). */
        if (g_apu_state && recomp_env(RENV_APU_FAULT_BENCH)) {
            extern double apu_hook_fault_bench(unsigned n);
            apu_hook_fault_bench((unsigned)atoi(recomp_env(RENV_APU_FAULT_BENCH)));
        }
    }
#endif

    /* Step 5: Initialize Xbox kernel */
    printf("Initializing Xbox kernel replacement...\n");
    xbox_kernel_init();

    /* Step 6: Set game directory for file I/O path translation */
    {
        extern void xbox_path_init(const char *game_dir, const char *save_dir);
        xbox_path_init(BLINX2_GAME_DIR, NULL);
    }

    /* Step 7: Initialize kernel bridge (thunk table in Xbox memory) */
    printf("Initializing kernel bridge...\n");
    xbox_kernel_bridge_init();

    /* Step 8: Initialize stack */
    g_esp = XBOX_STACK_TOP;

    /* Skip XAPI's utility-drive mount (XBE init flag XINIT_MOUNT_UTILITY_DRIVE).
     *
     * With the flag set, XapiInitProcess calls XMountUtilityDrive, which opens
     * the raw disk \Device\Harddisk0\partition0 to read the partition table.
     * The toolkit backs that device with an image file on Windows only (and
     * none ships with the game); on POSIX the path is unrecognized, the open fails, and XAPI boots to the
     * dashboard with XLD_ERROR_INVALID_HARD_DISK before the game starts.
     * Z:\ needs no mount here -- the path layer maps it to the save Cache
     * directory regardless. The header is in guest memory, which is where
     * XAPI reads the flags from.
     *
     * Cleared on every host, Windows too: one boot path everywhere, and
     * Proton is not left as the only host exercising the untested
     * Partition0.img route. */
    {
        volatile uint32_t *init_flags =
            (volatile uint32_t *)((uint8_t *)g_xbox_mem_offset + 0x00010124u);
        if (*init_flags & 1u) {
            *init_flags &= ~1u;
            printf("[BOOT] XBE init flag MOUNT_UTILITY_DRIVE cleared "
                   "(no raw-disk mount)\n");
        }
    }

    /*
     * No CRT globals are pre-initialized: BLiNX 2's CRT heap init (__heap_init,
     * __active_heap) runs as recompiled and needs no help from the host.
     */

    printf("\n=== Initialization complete ===\n");
    printf("Entry point: 0x%08X\n", BLINX2_ENTRY_POINT);
    printf("ESP: 0x%08X\n", g_esp);

    /* Build the flat dispatch table before the guest runs.
     *
     * Without this recomp_lookup falls back to a binary search over the
     * whole function table -- roughly log2(n) branches on *every*
     * indirect call, which for a 45,000-function C++ title is about 16
     * every time the game goes through a vtable. Half-Life 2 spent most
     * of its static initialisation inside recomp_lookup for exactly this
     * reason, and it read as a hang.
     *
     * Optional by design: if the allocation fails the search still works,
     * so a failure is worth one line and not a fatal error. */
    if (!recomp_dispatch_init())
        fprintf(stderr, "[BOOT] flat dispatch unavailable; "
                        "indirect calls will use the binary search\n");

    /* Arm the hang watchdog. Does nothing unless RECOMP_WATCHDOG_SECS is set,
     * and must be called from this thread -- the guest registers it samples are
     * thread-local, so it has to be handed the copies belonging to the thread
     * that runs guest code.
     *
     * Not optional boilerplate: without this call RECOMP_WATCHDOG_SECS is
     * silently inert, and the one diagnostic that tells a hang from slowness
     * does nothing while appearing to be set. */
    xbox_WatchdogStart();

    { extern void cat_save_seed(void); cat_save_seed(); }   /* RECOMP_SAVE_SEED into RECOMP_SAVE_DIR */
    { extern void cat_pad_early_init(void); cat_pad_early_init(); } /* scripted pad: see file opens */

    /* Step 9: Call the recompiled entry point */
    printf("\nStarting game...\n");
    fflush(stdout);

    xbe_entry_point();

    printf("\nGame returned. Cleaning up...\n");

    /* Cleanup */
    xbox_kernel_shutdown();
    xbox_MemoryLayoutShutdown();
    free(xbe_data);

    return 0;
}

/* ── XBE Loading ───────────────────────────────────────────── */

static BOOL load_xbe(const char *path, void **out_data, size_t *out_size)
{
    FILE *f = fopen(path, "rb");
    if (!f) {
        fprintf(stderr, "Cannot open XBE: %s\n", path);
        return FALSE;
    }

    fseek(f, 0, SEEK_END);
    long size = ftell(f);
    fseek(f, 0, SEEK_SET);

    if (size <= 0) {
        fclose(f);
        return FALSE;
    }

    void *data = malloc((size_t)size);
    if (!data) {
        fclose(f);
        return FALSE;
    }

    if (fread(data, 1, (size_t)size, f) != (size_t)size) {
        free(data);
        fclose(f);
        return FALSE;
    }

    fclose(f);
    *out_data = data;
    *out_size = (size_t)size;
    return TRUE;
}

